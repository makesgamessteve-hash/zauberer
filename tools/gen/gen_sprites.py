"""Generates the mana-mote sprite sheet (sprites/mote.png + sprites/mote.lua)."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from pngw import write_png  # noqa: E402

FRAME = 16
FRAMES = 4
PALETTE = [(255, 240, 255), (200, 150, 255), (140, 90, 230), (80, 40, 160)]


def main(out_dir):
    width, height = FRAME * FRAMES, FRAME
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for f in range(FRAMES):
        radius = 3.0 + 1.5 * math.sin(f / FRAMES * 2 * math.pi) + 2.0
        for y in range(FRAME):
            for x in range(FRAME):
                d = math.hypot(x + 0.5 - FRAME / 2, y + 0.5 - FRAME / 2)
                if d <= radius:
                    band = min(3, int(d / radius * 4))
                    r, g, b = PALETTE[band]
                    pixels[y][f * FRAME + x] = (r, g, b, 255)
    os.makedirs(out_dir, exist_ok=True)
    write_png(os.path.join(out_dir, "mote.png"), width, height, pixels)
    with open(os.path.join(out_dir, "mote.lua"), "w", encoding="utf-8") as f:
        f.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        f.write("-- Generated by tools/gen/gen_sprites.py. Do not edit.\n")
        f.write("return {\n")
        f.write('  texture = "sprites/mote.png",\n')
        f.write("  frame_width = %d,\n  frame_height = %d,\n  frames = %d,\n  fps = 8,\n" % (FRAME, FRAME, FRAMES))
        f.write("  pivot = { 0.5, 0.5 },\n  size = { 0.35, 0.35 },\n")
        f.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "assets/base/sprites")
