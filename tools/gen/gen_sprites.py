"""Generates the mana-mote, flame, smoke, rain, snow and insect sprites (sprites/mote.*, flame.*, smoke.*, ...)."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from pngw import write_png  # noqa: E402

FRAME = 16
FRAMES = 4
PALETTE = [(255, 240, 255), (200, 150, 255), (140, 90, 230), (80, 40, 160)]


def main(out_dir):
    width, height = FRAME * FRAMES, FRAME
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for f in range(FRAMES):
        radius = 3.0 + 1.5 * math.sin(f / FRAMES * 2 * math.pi) + 2.0
        for y in range(FRAME):
            for x in range(FRAME):
                d = math.hypot(x + 0.5 - FRAME / 2, y + 0.5 - FRAME / 2)
                if d <= radius:
                    band = min(3, int(d / radius * 4))
                    r, g, b = PALETTE[band]
                    pixels[y][f * FRAME + x] = (r, g, b, 255)
    os.makedirs(out_dir, exist_ok=True)
    write_png(os.path.join(out_dir, "mote.png"), width, height, pixels)
    with open(os.path.join(out_dir, "mote.lua"), "w", encoding="utf-8") as f:
        f.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        f.write("-- Generated by tools/gen/gen_sprites.py. Do not edit.\n")
        f.write("return {\n")
        f.write('  texture = "sprites/mote.png",\n')
        f.write("  frame_width = %d,\n  frame_height = %d,\n  frames = %d,\n  fps = 8,\n" % (FRAME, FRAME, FRAMES))
        f.write("  pivot = { 0.5, 0.5 },\n  size = { 0.35, 0.35 },\n")
        f.write("}\n")
    flame(out_dir)
    smoke(out_dir)
    precipitation(out_dir)
    insects(out_dir)


FLAME_W, FLAME_H, FLAME_FRAMES = 16, 24, 6
# White-yellow core, orange body, red tips: a hot-to-cool ramp.
FLAME_PALETTE = [(255, 246, 200), (255, 214, 90), (250, 150, 40), (220, 80, 30), (150, 40, 25)]


def _flame_noise(x, y, f):
    """A small deterministic hash noise in 0..1 (no random module)."""
    h = (x * 374761393 + y * 668265263 + f * 2147483647) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h ^ (h >> 16)) & 0xFFFF) / 65535.0


def flame(out_dir):
    """An animated flame, its pivot at the bottom (sprites/flame.png + .lua)."""
    width, height = FLAME_W * FLAME_FRAMES, FLAME_H
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for f in range(FLAME_FRAMES):
        phase = f / FLAME_FRAMES * 2 * math.pi
        for y in range(FLAME_H):
            up = (FLAME_H - 1 - y) / (FLAME_H - 1)  # 0 at the bottom, 1 at the top
            sway = 1.6 * math.sin(phase + up * 3.0) * up
            half = (FLAME_W / 2 - 1) * (1.0 - up ** 1.4) * (0.85 + 0.15 * math.sin(phase * 2 + up * 5))
            for x in range(FLAME_W):
                d = abs(x + 0.5 - FLAME_W / 2 - sway)
                edge = half - 1.2 * _flame_noise(x, y, f)
                if d > edge or half <= 0.3:
                    continue
                heat = (1.0 - d / max(edge, 0.5)) * (1.0 - 0.8 * up)
                band = 4 - min(4, int(heat * 5.0))
                r, g, b = FLAME_PALETTE[band]
                pixels[y][f * FLAME_W + x] = (r, g, b, 255)
    write_png(os.path.join(out_dir, "flame.png"), width, height, pixels)
    with open(os.path.join(out_dir, "flame.lua"), "w", encoding="utf-8") as fh:
        fh.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        fh.write("-- Generated by tools/gen/gen_sprites.py. Do not edit.\n")
        fh.write("return {\n")
        fh.write('  texture = "sprites/flame.png",\n')
        fh.write("  frame_width = %d,\n  frame_height = %d,\n  frames = %d,\n  fps = 10,\n"
                 % (FLAME_W, FLAME_H, FLAME_FRAMES))
        fh.write("  pivot = { 0.5, 0.0 },\n  size = { 1.6, 2.4 },\n")
        fh.write("}\n")


SMOKE = 16
SMOKE_FRAMES = 4
SMOKE_PALETTE = [(196, 192, 186), (160, 156, 152), (124, 122, 120)]
BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def smoke(out_dir):
    """A smoke puff, dithered (sprites are alpha-tested), that billows over
    its frames (sprites/smoke.png + .lua)."""
    width, height = SMOKE * SMOKE_FRAMES, SMOKE
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for f in range(SMOKE_FRAMES):
        phase = f / SMOKE_FRAMES * 2 * math.pi
        for y in range(SMOKE):
            for x in range(SMOKE):
                dx, dy = x + 0.5 - SMOKE / 2, y + 0.5 - SMOKE / 2
                angle = math.atan2(dy, dx)
                lobes = 1.0 + 0.18 * math.sin(3 * angle + phase) + 0.1 * math.sin(5 * angle - phase)
                d = math.hypot(dx, dy) / (SMOKE / 2 - 1) / lobes
                density = 1.0 - d * d  # thick in the middle, thin at the edge
                if density * 16 <= BAYER4[y % 4][x % 4]:
                    continue
                shade = 0 if dy < -1 else (1 if dy < 3 else 2)  # lit from above
                r, g, b = SMOKE_PALETTE[shade]
                pixels[y][f * SMOKE + x] = (r, g, b, 255)
    write_png(os.path.join(out_dir, "smoke.png"), width, height, pixels)
    with open(os.path.join(out_dir, "smoke.lua"), "w", encoding="utf-8") as fh:
        fh.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        fh.write("-- Generated by tools/gen/gen_sprites.py. Do not edit.\n")
        fh.write("return {\n")
        fh.write('  texture = "sprites/smoke.png",\n')
        fh.write("  frame_width = %d,\n  frame_height = %d,\n  frames = %d,\n  fps = 3,\n" % (SMOKE, SMOKE, SMOKE_FRAMES))
        fh.write("  pivot = { 0.5, 0.5 },\n  size = { 6.0, 6.0 },\n")
        fh.write("}\n")



def _single(out_dir, name, pixels_fn, w, h, size, comment):
    pixels = [[(0, 0, 0, 0)] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            c = pixels_fn(x, y)
            if c:
                pixels[y][x] = c
    write_png(os.path.join(out_dir, name + ".png"), w, h, pixels)
    with open(os.path.join(out_dir, name + ".lua"), "w", encoding="utf-8") as fh:
        fh.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        fh.write("-- Generated by tools/gen/gen_sprites.py. Do not edit. %s\n" % comment)
        fh.write("return {\n")
        fh.write('  texture = "sprites/%s.png",\n' % name)
        fh.write("  frame_width = %d,\n  frame_height = %d,\n  frames = 1,\n" % (w, h))
        fh.write("  pivot = { 0.5, 0.5 },\n  size = { %.2f, %.2f },\n" % size)
        fh.write("}\n")


def precipitation(out_dir):
    """A raindrop's streak and a snowflake (sprites/rain.*, sprites/snow.*)."""
    _single(out_dir, "rain", lambda x, y: (190, 205, 225, 255) if x == 1 else None, 3, 12, (0.06, 0.9),
            "A falling raindrop.")
    flake = {(1, 0), (0, 1), (1, 1), (2, 1), (1, 2)}
    _single(out_dir, "snow", lambda x, y: (240, 244, 250, 255) if (x, y) in flake else None, 3, 3, (0.12, 0.12),
            "A snowflake.")


def _from_rows(rows, colours):
    """Pixels from rows of characters, each a key of colours ('.' is clear)."""
    return lambda x, y: colours.get(rows[y][x]) if rows[y][x] != "." else None


def insects(out_dir):
    """Bees, mosquitoes, fireflies and butterflies for the swarms (sprites/bee.*, ...)."""
    bee = ["..w.w..",
           ".kykyk.",
           "kykykyk",
           ".kykyk."]
    _single(out_dir, "bee", _from_rows(bee, {"w": (230, 240, 255, 200), "k": (40, 30, 20, 255),
                                             "y": (240, 190, 40, 255)}), 7, 4, (0.07, 0.04), "A bee.")
    mosquito = ["w...w",
                ".w.w.",
                "..k..",
                ".k.k."]
    _single(out_dir, "mosquito", _from_rows(mosquito, {"w": (200, 205, 210, 150), "k": (50, 45, 45, 255)}),
            5, 4, (0.04, 0.03), "A mosquito.")
    firefly = [".ggg.",
               "gGYGg",
               "gYWYg",
               "gGYGg",
               ".ggg."]
    _single(out_dir, "firefly", _from_rows(firefly, {"g": (120, 200, 60, 90), "G": (170, 240, 90, 170),
                                                     "Y": (230, 255, 120, 230), "W": (255, 255, 220, 255)}),
            5, 5, (0.14, 0.14), "A firefly's glow.")
    butterfly = ["oo.k.oo",
                 "ooo.ooo",
                 ".ookoo.",
                 ".oo.oo."]
    _single(out_dir, "butterfly", _from_rows(butterfly, {"o": (240, 140, 40, 255), "k": (30, 25, 25, 255)}),
            7, 4, (0.1, 0.06), "A butterfly.")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "assets/base/sprites")
