"""Generates the invented scripts of the style families (concept 10.8): one
5x7 pixel font per script (fonts/script_<name>.png + .lua) whose letters a-z
are glyphs of that script, so a transliterated word drawn with it shows the
people's own writing. Each script has its own stroke vocabulary; every glyph
is a deterministic hash of the script and the letter.

The glyph shapes are original work of the Zauberer project (CC BY 4.0)."""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from pngw import write_png  # noqa: E402

SCRIPTS = ["nastal", "qalam", "khachar", "runic", "tifin", "akshara", "brush"]
LETTERS = " abcdefghijklmnopqrstuvwxyz"
COLUMNS = 16
CELL = 8


def _rng(script, letter):
    h = hashlib.sha256(("%s:%s" % (script, letter)).encode()).digest()
    state = [int.from_bytes(h[:8], "little")]

    def nxt(n):
        state[0] = (state[0] * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
        return (state[0] >> 33) % n
    return nxt


def _glyph(script, letter):
    g = [[0] * 5 for _ in range(7)]
    if letter == " ":
        return g
    r = _rng(script, letter)

    def put(x, y):
        if 0 <= x < 5 and 0 <= y < 7:
            g[y][x] = 1

    def line(x0, y0, x1, y1):
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            put(round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n))

    if script in ("nastal", "qalam"):  # flowing: a baseline swash, a rise, dots
        base = 5 if script == "nastal" else 4
        line(r(2), base, 4, base)
        x = r(5)
        line(x, base, x, 1 + r(3))
        if r(2):
            line(0, base - 1, 1, base)
        for _ in range(r(3)):
            put(r(5), 0 if r(2) else 6)
    elif script == "khachar":  # rounded blocks
        x0, x1 = r(2), 3 + r(2)
        y0, y1 = 1 + r(2), 4 + r(3)
        line(x0, y0, x1, y0)
        line(x0, y0, x0, y1)
        if r(2):
            line(x1, y0, x1, y1)
        else:
            line(x0, y1, x1, y1)
        put(x0, y0)
    elif script == "runic":  # angular staves
        x = 1 + r(3)
        line(x, 0, x, 6)
        for _ in range(1 + r(2)):
            y = r(5)
            line(x, y, x + (1 if r(2) else -1) * 2, y + 2)
    elif script == "tifin":  # circles, dots and crosses
        kind = r(3)
        if kind == 0:
            for (x, y) in ((1, 1), (2, 0), (3, 1), (4, 3), (3, 5), (2, 6), (1, 5), (0, 3)):
                put(x, y)
        elif kind == 1:
            line(2, 0, 2, 6)
            line(0, 3, 4, 3)
        else:
            for _ in range(2 + r(3)):
                put(r(5), r(7))
        if r(2):
            put(2, 3)
    elif script == "akshara":  # a headline with forms hanging below
        line(0, 0, 4, 0)
        x = r(5)
        line(x, 0, x, 6)
        y = 2 + r(3)
        line(0, y, x, y + r(2))
        if r(2):
            put(4 - r(2), 5)
    else:  # brush: dense crossing strokes
        for _ in range(3):
            if r(2):
                y = r(7)
                line(r(2), y, 3 + r(2), y)
            else:
                x = r(5)
                line(x, r(3), x, 4 + r(3))
    return g


def main(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    rows = (len(LETTERS) + COLUMNS - 1) // COLUMNS
    width, height = COLUMNS * CELL, rows * CELL
    for script in SCRIPTS:
        pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
        for index, ch in enumerate(LETTERS):
            cx, cy = (index % COLUMNS) * CELL, (index // COLUMNS) * CELL
            for y, row in enumerate(_glyph(script, ch)):
                for x, bit in enumerate(row):
                    if bit:
                        pixels[cy + y][cx + x] = (255, 255, 255, 255)
        write_png(os.path.join(out_dir, "script_%s.png" % script), width, height, pixels)
        with open(os.path.join(out_dir, "script_%s.lua" % script), "w", encoding="utf-8") as f:
            f.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
            f.write("-- Generated by tools/gen/gen_scripts.py. Do not edit.\n")
            f.write("return {\n")
            f.write('  texture = "fonts/script_%s.png",\n' % script)
            f.write("  glyph_width = %d,\n  glyph_height = %d,\n  columns = %d,\n  advance = 6,\n"
                    % (CELL, CELL, COLUMNS))
            f.write('  chars = "%s",\n' % LETTERS)
            f.write('  replacement = " ",\n')
            f.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "assets/base/fonts")
