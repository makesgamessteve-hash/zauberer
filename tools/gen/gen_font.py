SQUEEZE = (0, 2, 3, 4, 6)  # the rows a capital keeps under a mark


def compose(ch):
    """A glyph (7 or 8 rows) for a letter with diacritics, or None."""
    import unicodedata
    parts = unicodedata.normalize("NFD", ch)
    base, marks = parts[0], parts[1:]
    if base not in GLYPHS or not marks:
        return None
    rows = list(GLYPHS[base]) + [0]
    for m in marks:
        if m in MARKS_BELOW:
            rows[7] |= MARKS_BELOW[m]
        elif base.isupper():
            squeezed = [GLYPHS[base][r] for r in SQUEEZE]
            rows = [MARKS[m], 0] + squeezed + [rows[7]]
        elif base in "dlt" and rows[0]:  # a caron beside a tall letter
            rows[0] |= 0x01
            rows[1] |= 0x01
        else:  # small letters (i and j lose their dot to the mark)
            rows[0] = MARKS[m]
    return rows if rows[7] else rows[:7]


def all_glyphs():
    glyphs = dict(GLYPHS)
    replacement = glyphs.pop("\u25a1")
    for ch in EXTENDED:
        rows = compose(ch)
        if rows and ch not in glyphs:
            glyphs[ch] = rows
    for ch, rows in SPECIAL.items():
        glyphs.setdefault(ch, rows)
    glyphs["\u25a1"] = replacement  # the replacement glyph stays last
    return glyphs


def main(out_dir):
    glyphs = all_glyphs()
    chars = list(glyphs.keys())
    rows = (len(chars) + COLUMNS - 1) // COLUMNS
    width, height = COLUMNS * CELL, rows * CELL
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    for index, ch in enumerate(chars):
        cx, cy = (index % COLUMNS) * CELL, (index // COLUMNS) * CELL
        for y, bits in enumerate(glyphs[ch]):
            for x in range(5):
                if bits & (0x10 >> x):
                    pixels[cy + y][cx + x] = (255, 255, 255, 255)
    os.makedirs(out_dir, exist_ok=True)
    write_png(os.path.join(out_dir, "pixel.png"), width, height, pixels)
    lua_chars = "".join(chars).replace("\\", "\\\\").replace('"', '\\"')
    with open(os.path.join(out_dir, "pixel.lua"), "w", encoding="utf-8") as f:
        f.write("-- SPDX-License-Identifier: CC-BY-4.0\n")
        f.write("-- Generated by tools/gen/gen_font.py. Do not edit.\n")
        f.write("return {\n")
        f.write('  texture = "fonts/pixel.png",\n')
        f.write("  glyph_width = %d,\n  glyph_height = %d,\n  columns = %d,\n  advance = 6,\n" % (CELL, CELL, COLUMNS))
        f.write('  chars = "%s",\n' % lua_chars)
        f.write('  replacement = "\\u{25A1}",\n')
        f.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "assets/base/fonts")
